export const MICRO_H = 5;

/** Width in pixels of `text` (3 per glyph, 1 between glyphs). */
export function microWidth(text: string): number {
  return text.length ? text.length * 4 - 1 : 0;
}

/** Rows of `text` with `ink` for set pixels and `blank` elsewhere. */
export function microRows(text: string, ink: string, blank = "."): string[] {
  const rows: string[] = [];
  for (let y = 0; y < MICRO_H; y++) {
    rows.push(
      [...text]
        .map((ch) => {
          const g = MICRO[ch.toUpperCase()];
          if (!g) throw new Error(`no micro glyph for "${ch}"`);
          return g[y].replaceAll("#", ink).replaceAll(".", blank);
        })
        .join(blank),
    );
  }
  return rows;
}
